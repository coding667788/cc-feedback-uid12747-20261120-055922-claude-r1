"""Stable error codes returned by the simulator (see README for the table)."""


class Err:
    DEVICE_EXISTS = "ERR_DEVICE_EXISTS"
    DEVICE_NOT_FOUND = "ERR_DEVICE_NOT_FOUND"
    KEY_NOT_FOUND = "ERR_KEY_NOT_FOUND"
    SIGNER_REVOKED = "ERR_SIGNER_REVOKED"
    BAD_SIGNATURE = "ERR_BAD_SIGNATURE"
    UNKNOWN_OBJECT = "ERR_UNKNOWN_OBJECT"
    OBJECT_CONFLICT = "ERR_OBJECT_CONFLICT"
    DUPLICATE_PATH = "ERR_DUPLICATE_PATH"
    BATCH_NOT_FOUND = "ERR_BATCH_NOT_FOUND"
    BATCH_CLOSED = "ERR_BATCH_CLOSED"
    BATCH_COMPLETE = "ERR_BATCH_COMPLETE"
    DUPLICATE_SEGMENT = "ERR_DUPLICATE_SEGMENT"
    SCOPE_MISMATCH = "ERR_SCOPE_MISMATCH"
    INCOMPLETE_OBSERVATION = "ERR_INCOMPLETE_OBSERVATION"
    OBSERVATION_MISMATCH = "ERR_OBSERVATION_MISMATCH"
    BASELINE_NOT_FOUND = "ERR_BASELINE_NOT_FOUND"
    GENERATION_CHANGED = "ERR_GENERATION_CHANGED"
    BASELINE_SWAPPED = "ERR_BASELINE_SWAPPED"
    PRECHECK_NOT_FOUND = "ERR_PRECHECK_NOT_FOUND"
    RECEIPT_NOT_FOUND = "ERR_RECEIPT_NOT_FOUND"
    UNKNOWN_OP = "ERR_UNKNOWN_OP"


class EngineError(Exception):
    """Domain error carrying a stable machine-readable code."""

    def __init__(self, code: str, detail: str = ""):
        super().__init__(f"{code}: {detail}")
        self.code = code
        self.detail = detail
